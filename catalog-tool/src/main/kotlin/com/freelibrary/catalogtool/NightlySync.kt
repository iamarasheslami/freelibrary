package com.freelibrary.catalogtool

import com.freelibrary.shared.BookExport
import com.freelibrary.shared.Manifest
import com.freelibrary.shared.ManifestEntry
import java.nio.file.Path
import java.time.LocalDate

/**
 * What the nightly sync should write for a book, or null when there is nothing to write.
 *
 * Gutenberg's feed also lists books whose catalog entry was only touched, so a book can come back with
 * every field the same as the file already written. Writing it again with today's date would make every
 * app download and rewrite a book that did not change, and report it as an update. [fresh] already
 * carries today's date; when it is [previous] in everything else, the old file and its date stay.
 */
internal fun changedExport(
    fresh: BookExport,
    previous: BookExport?,
): BookExport? = if (previous != null && previous == fresh.copy(lastModified = previous.lastModified)) null else fresh

private const val TODAY_RSS_URL = "https://www.gutenberg.org/cache/epub/feeds/today.rss"

/**
 * Entry point for the nightly incremental sync: checks Project Gutenberg's
 * today.rss feed for books posted or updated in the last 24 hours, fetches
 * only those individual books' RDF directly, and updates the checked-out
 * freelibrary-catalog-data export (manifest.json + books/) in place.
 *
 * Deliberately does not touch the bundled catalog.sqlite - that is only
 * regenerated by the full pipeline (see [main] in Main.kt), on a much less
 * frequent, deliberate schedule. This entry point exists specifically to
 * keep existing installs current via the app's own sync client, without
 * ever needing a full ~126MB archive re-download for a handful of new
 * books. Run via `./gradlew :catalog-tool:nightlySync`.
 */
fun main() {
    val exportDir = Path.of("data/export")
    val exportBooksDir = exportDir.resolve("books")
    val today = LocalDate.now().toString()

    val bookIds =
        try {
            parseRssBookIds(fetchBytes(TODAY_RSS_URL))
        } catch (e: Exception) {
            println("Failed to fetch or parse today.rss: ${e.message}")
            return
        }

    println("Found ${bookIds.size} book id(s) in today's feed.")

    val existingManifest = readManifest(exportDir)
    val manifestEntries = existingManifest?.books?.associateBy { it.externalId }?.toMutableMap() ?: mutableMapOf()
    val baselineVersion = existingManifest?.baselineVersion ?: today

    var updatedCount = 0
    var unchangedCount = 0
    var skippedCount = 0
    var failedCount = 0
    val failureSamples = mutableListOf<String>()

    for (externalId in bookIds) {
        try {
            Thread.sleep(200)
            val rdfBytes = fetchBytes("https://www.gutenberg.org/cache/epub/$externalId/pg$externalId.rdf")
            val book = parseRdf(rdfBytes)
            if (book == null) {
                skippedCount++
                continue
            }

            val changed = changedExport(book.toExport(lastModified = today), readBookExport(exportBooksDir, externalId))
            if (changed == null) {
                unchangedCount++
                continue
            }

            writeBookExport(exportBooksDir, changed)
            manifestEntries[externalId] = ManifestEntry(externalId = externalId, lastModified = today)
            updatedCount++
        } catch (e: Exception) {
            failedCount++
            if (failureSamples.size < 5) {
                failureSamples.add("$externalId: ${e.message}")
            }
        }
    }

    writeManifest(
        exportDir,
        Manifest(generatedAt = today, baselineVersion = baselineVersion, books = manifestEntries.values.toList()),
    )

    println("Done. Updated: $updatedCount, unchanged: $unchangedCount, skipped: $skippedCount, failed: $failedCount")
    if (failureSamples.isNotEmpty()) {
        println("Sample failures:")
        failureSamples.forEach { println("  $it") }
    }
}
